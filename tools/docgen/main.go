// Command docgen writes docs/checks.md, the list of what telltale checks,
// from the hardening checklist (checklist.Items) and the heuristics
// (heuristics.Rules), so the page always says what the code does.
//
// Usage, from the repository root:
//
//	go run ./tools/docgen            # write docs/checks.md
//	go run ./tools/docgen -check     # exit 1 if docs/checks.md is stale
//
// A test (TestDocsChecksUpToDate) runs the check, so a change to an item or
// a rule that is not followed by a regenerated page fails go test.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"strings"

	"github.com/donaldsteele/telltale/internal/checklist"
	"github.com/donaldsteele/telltale/internal/heuristics"
	"github.com/donaldsteele/telltale/internal/model"
)

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}

func run(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("docgen", flag.ContinueOnError)
	fs.SetOutput(stderr)
	out := fs.String("out", "docs/checks.md", "the file to write or check")
	check := fs.Bool("check", false, "only check that the file is up to date; exit 1 if it is not")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	page, err := render()
	if err != nil {
		fmt.Fprintln(stderr, "docgen:", err)
		return 1
	}
	if *check {
		have, err := os.ReadFile(*out)
		if err != nil {
			fmt.Fprintf(stderr, "docgen: %v; write it with: go run ./tools/docgen\n", err)
			return 1
		}
		if !bytes.Equal(have, page) {
			fmt.Fprintf(stderr, "docgen: %s is stale: the checklist or the heuristics changed; regenerate it with: go run ./tools/docgen\n", *out)
			return 1
		}
		fmt.Fprintf(stdout, "%s is up to date\n", *out)
		return 0
	}
	if err := os.WriteFile(*out, page, 0o644); err != nil {
		fmt.Fprintln(stderr, "docgen:", err)
		return 1
	}
	fmt.Fprintf(stdout, "wrote %s\n", *out)
	return 0
}

// groups names the checklist's sections by the middle of the item ID
// (TT-SSH-001 is in SSH), in the order the checklist has them.
var groups = map[string]string{
	"SSH":  "SSH server",
	"ACCT": "Accounts",
	"SUDO": "sudo",
	"FILE": "File permissions",
	"FW":   "Firewall",
	"KERN": "Kernel settings",
	"SVC":  "Services",
}

func render() ([]byte, error) {
	var b strings.Builder
	items := checklist.Items()
	rules := heuristics.Rules()
	b.WriteString(`<!-- Generated by tools/docgen from the checklist and the heuristics. Do not edit: run "go run ./tools/docgen". -->

# What telltale checks

telltale has three kinds of check:

1. **Changes since the snapshot**, when there is one: every difference
   between the machine now and the known-good snapshot, with changes that a
   signed package update explains set apart. See
   [how it works](how-it-works.md).
2. **The hardening checklist** below: settings any well-run machine should
   have.
3. **Suspicious on any machine**, below: things worth a look whether or not
   there is a snapshot.

Package-owned files are also checked against the distribution's signed
packages (see [how it works](how-it-works.md)).

Every finding has a severity. From the highest:

- **tampering**: a checklist item that passed in the snapshot and fails now
  (the regression rule), something the machine's own tools hide, or a
  system file that does not match its signed package;
- **backdoor sign**: something that gives someone a way in or hides one;
- **weak setting**: a setting that should be stricter;
- **note**: worth knowing, not a problem by itself.

Every finding in a report also carries its ID (for ` + "`telltale accept`" + ` and
the web UI's exceptions), the evidence, and the exact command that would
fix it on that machine. telltale never runs a fix itself.

`)
	fmt.Fprintf(&b, "## The hardening checklist\n\n%d items. A failing item is a weak setting. An item that passed in the known-good snapshot and fails now is raised to tampering, because attackers loosen these settings to keep a way back in. An item whose input could not be read (most need root) is listed as skipped, never guessed. References are to the DISA STIG for Ubuntu 22.04 where a rule applies; the other items are telltale's own.\n", len(items))
	cur := ""
	for _, it := range items {
		parts := strings.Split(it.ID, "-")
		if len(parts) != 3 {
			return nil, fmt.Errorf("checklist item %q: not of the form TT-GROUP-NNN", it.ID)
		}
		g, ok := groups[parts[1]]
		if !ok {
			return nil, fmt.Errorf("checklist item %s: no section name for %s in tools/docgen", it.ID, parts[1])
		}
		if g != cur {
			fmt.Fprintf(&b, "\n### %s\n\n", g)
			cur = g
		}
		fmt.Fprintf(&b, "- **%s** %s.\n  %s", it.ID, sentence(it.Title), oneLine(it.Why))
		if len(it.Refs) > 0 {
			fmt.Fprintf(&b, " *%s.*", strings.Join(it.Refs, ", "))
		}
		b.WriteString("\n")
	}

	fmt.Fprintf(&b, "\n## Suspicious on any machine\n\n%d kinds of finding, under %d IDs. These need no snapshot. The finding key (the ID a report shows for each finding) starts as given here and ends with the account, path or program it is about.\n\n", len(rules), countIDs(rules))
	for _, r := range rules {
		fmt.Fprintf(&b, "- **%s** %s. *%s.*\n  %s", r.ID, sentence(r.Title), capital(sevName(r.Severity)), oneLine(r.Why))
		if r.When != "" {
			fmt.Fprintf(&b, " %s", oneLine(r.When))
		}
		fmt.Fprintf(&b, "\n  Key: `%s`\n", r.Key)
	}
	return []byte(b.String()), nil
}

func countIDs(rules []heuristics.Rule) int {
	seen := map[string]bool{}
	for _, r := range rules {
		seen[r.ID] = true
	}
	return len(seen)
}

func sevName(s model.Severity) string { return s.String() }

// sentence drops a final full stop, which the page adds.
func sentence(s string) string { return strings.TrimSuffix(oneLine(s), ".") }

func capital(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// oneLine keeps a text on one Markdown line.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
